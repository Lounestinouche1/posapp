internal static class Rtl
{
    private sealed record Orig(int Left, DockStyle Dock);
    private static readonly ConditionalWeakTable<Control, Orig> Originals = new();

    public static void Apply(Control root)
    {
        if (Tr.Lang != "ar") return;
        root.RightToLeft = RightToLeft.Yes;
        Mirror(root);
    }

    private static void Mirror(Control parent)
    {
        foreach (Control c in parent.Controls)
        {
            if (!Originals.TryGetValue(c, out var orig))
            {
                orig = new Orig(c.Left, c.Dock);
                Originals.Add(c, orig);
                if (orig.Dock == DockStyle.Left) c.Dock = DockStyle.Right;
                else if (orig.Dock == DockStyle.Right) c.Dock = DockStyle.Left;
            }
            if (orig.Dock == DockStyle.None && parent.ClientSize.Width > 0 && c.Width <= parent.ClientSize.Width)
                c.Left = parent.ClientSize.Width - orig.Left - c.Width;
            if (c.RightToLeft != RightToLeft.Yes) c.RightToLeft = RightToLeft.Yes;
            Mirror(c);
        }
    }
}
